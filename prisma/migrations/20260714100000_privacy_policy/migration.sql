### 제7조 (개인정보의 파기)


① 본 학회는 개인정보 보유기간의 경과, 처리목적 달성 등 개인정보가 불필요하게 되었을 때에는 지체없이 해당 개인정보를 파기합니다.

② 정보주체로부터 동의받은 개인정보 보유기간이 경과하거나 처리목적이 달성되었음에도 불구하고 다른 법령에 따라 개인정보를 계속 보존하여야 하는 경우에는, 해당 개인정보를 별도의 데이터베이스(DB)로 옮기거나 보관장소를 달리하여 보존합니다.

③ 개인정보 파기의 절차 및 방법은 다음과 같습니다.

가. 파기절차: 본 학회는 파기 사유가 발생한 개인정보를 선정하고, 본 학회의 개인정보 보호책임자의 승인을 받아 개인정보를 파기합니다.

나. 파기방법: 전자적 파일 형태로 기록 · 저장된 개인정보는 기록을 재생할 수 없도록 안전하게 삭제합니다. 종이 문서에 기록 · 저장된 개인정보는 분쇄기로 분쇄하거나 소각하여 파기합니다.


### 제8조 (개인정보의 안전성 확보조치)


본 학회는 개인정보의 안전성 확보를 위해 다음과 같은 조치를 취하고 있습니다.

① 관리적 조치: 내부관리계획 수립 · 시행, 개인정보 취급 담당자의 최소화 및 교육

② 기술적 조치: 개인정보처리시스템 등의 접근권한 관리, 접근통제시스템 설치, 고유식별정보 등의 암호화(비밀번호 일방향 암호화 저장), 보안프로그램 설치 및 갱신

③ 물리적 조치: 전산실, 자료보관실 등의 접근통제


